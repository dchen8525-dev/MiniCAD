    @Test
    void shouldTrimBSplineFacesInFanSampleToTheirOwnBounds() throws IOException {
        String obj = StepMeshExporter.exportObj(Files.readString(Path.of("samples/fan.stp")));

        long triangles = obj.lines().filter(line -> line.startsWith("f ")).count();
        // 120 of the 194 faces are B-spline patches. With no mapper for those the
        // exporter fell back to gridding each whole surface, including the area the
        // face is trimmed away from (~995k triangles for the sample). The parametric
        // grid is capped at the preview's base density, which keeps this at a quarter
        // of the count produced when every face was refined to 64x48. Seam loops now
        // close through the preview's periodic normalizer: the mesh-local copy left
        // the closing sample on the previous sample's branch, one period away from
        // the first point, which inflated the loop bounds and covered the cells the
        // preview does not (22 triangles here). Planar trims bounded by CIRCLE arcs
        // now sample each arc over its own edge window instead of the whole circle,
        // which adds the 70 triangles the repeated samples had collapsed.
        assertEquals(200_739, triangles);
    }

